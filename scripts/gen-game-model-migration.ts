// scripts/gen-game-model-migration.ts
// Generates supabase/migrations/0089_manager_game_models.sql from
// scripts/seed/manager-game-models.json: each manager's full game model (his
// style preset with his personal adjustments applied, validated by the
// engine's own parser), written to entities.meta.game_model through
// managers.entity_id, with his profile rationale as a SQL comment.
//   npx tsx scripts/gen-game-model-migration.ts

import { writeFileSync } from 'node:fs';
import { parseGameModel, presetFor } from '../src/features/match/logic/spatial/gameModel';
import { managerSeeds } from './lib/islSquads';

const seeds = Object.values(managerSeeds());
const out: string[] = [
  '-- 0089_manager_game_models.sql',
  "-- Seeds every manager's game model (docs/phases-of-play.md 3.2): the coaching",
  '-- choices per phase of play that the match engine reads through',
  '-- SpatialTeamInput.gameModel. Stored on the manager entity as',
  '-- entities.meta.game_model, reached through managers.entity_id, so it is',
  '-- universe data that staff, decrees, form or the Architect can change later.',
  '--',
  "-- Each model is the manager's style preset with one to three choices adjusted",
  '-- from his profile; the rationale for each adjustment is the comment above his',
  '-- update. Generated by scripts/gen-game-model-migration.ts from',
  '-- scripts/seed/manager-game-models.json.',
  '--',
  '-- Idempotent: each update only touches a row whose stored model differs, and',
  '-- jsonb_set keeps every other key of meta. A manager without an entity is',
  '-- skipped (the engine then uses his style preset).',
  '',
];
for (const s of seeds.sort((a, b) => a.club.localeCompare(b.club))) {
  const model = parseGameModel(s.style, s.game_model);
  const preset = presetFor(s.style);
  const changed = Object.keys(s.game_model).filter((k) => JSON.stringify((model as unknown as Record<string, unknown>)[k]) !== JSON.stringify((preset as unknown as Record<string, unknown>)[k]));
  if (changed.length !== Object.keys(s.game_model).length) throw new Error(`${s.manager}: an adjustment did not validate or equals the preset`);
  const json = JSON.stringify(model);
  out.push(`-- ${s.manager} (${s.club}, ${s.style} preset, ${s.formation}).`);
  out.push(`--   adjusts ${Object.keys(s.game_model).join(', ')} from the preset, because:`);
  for (const r of s.rationale) out.push(`--   - ${r}.`);
  out.push('UPDATE public.entities e');
  out.push(`   SET meta = jsonb_set(COALESCE(e.meta, '{}'::jsonb), '{game_model}', $gm$${json}$gm$::jsonb, true)`);
  out.push('  FROM public.managers m');
  out.push(` WHERE m.entity_id = e.id AND m.team_id = '${s.club}' AND m.name = '${s.manager.replace(/'/g, "''")}'`);
  out.push(`   AND (e.meta -> 'game_model') IS DISTINCT FROM $gm$${json}$gm$::jsonb;`);
  out.push('');
}
writeFileSync('supabase/migrations/0089_manager_game_models.sql', out.join('\n'));
console.log(`wrote ${seeds.length} managers`);
